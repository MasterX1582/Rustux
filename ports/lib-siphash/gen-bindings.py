import json

doc = json.load(open("rust/wrappers-rs/rust-anything.json"))
exports = doc["exports"]


def rs_ty(native):
    return {"uint64_t": "u64", "int64_t": "i64",
            "uint32_t": "u32", "int32_t": "i32"}[native]


lines = []
lines.append('//! C ABI for `wrappers.c`: drop-in replacements with the original names and signatures, generated')
lines.append('//! by rust-anything from `rust-anything.json`. All of the crate\'s `unsafe` code lives in this file.')
lines.append('')
lines.append('pub mod port;')
lines.append('')
for e in exports:
    name = e["name"]
    proto = e["prototype"]
    line = e["line"]
    params = [(p["name"], rs_ty(p["native_type"])) for p in e["params"]]
    ret = rs_ty(e["native_return"])
    sig = ", ".join(f"{n}: {t}" for n, t in params)
    call = ", ".join(n for n, _ in params)
    lines.append(f'/// `{proto}` (`wrappers.c:{line}`).')
    lines.append('#[cfg(not(feature = "shadow"))]')
    lines.append('// SAFETY: exported under the C name it replaces: link it instead of the original object.')
    lines.append('#[unsafe(no_mangle)]')
    lines.append(f'pub extern "C" fn {name}({sig}) -> {ret} {{')
    lines.append(f'    port::{name}({call})')
    lines.append('}')
    lines.append('')
    lines.append(f'/// `{name}` as `rust_anything_{name}`, for shadow builds beside the original.')
    lines.append('// SAFETY: a name no C code defines.')
    lines.append('#[unsafe(no_mangle)]')
    lines.append(f'pub extern "C" fn rust_anything_{name}({sig}) -> {ret} {{')
    lines.append(f'    port::{name}({call})')
    lines.append('}')
    lines.append('')
open("rust/wrappers-rs/src/lib.rs", "w", newline="\n").write("\n".join(lines) + "\n")

hdr = []
hdr.append('/* C API of the Rust port of `wrappers.c`, generated by rust-anything. */')
hdr.append('#ifndef WRAPPERS_RS_H')
hdr.append('#define WRAPPERS_RS_H')
hdr.append('')
hdr.append('#include <stdbool.h>')
hdr.append('#include <stddef.h>')
hdr.append('#include <stdint.h>')
hdr.append('#include <sys/types.h>')
hdr.append('')
for e in exports:
    hdr.append(e["prototype"] + ";")
hdr.append('')
hdr.append('/* The same functions under `rust_anything_` names, for shadow runs. */')
for e in exports:
    hdr.append(e["prototype"].replace("uint64_t " + e["name"],
                                      "uint64_t rust_anything_" + e["name"], 1) + ";")
hdr.append('')
hdr.append('#endif /* WRAPPERS_RS_H */')
open("rust/wrappers-rs/include/wrappers_rs.h", "w", newline="\n").write("\n".join(hdr) + "\n")
print("generated lib.rs and wrappers_rs.h for", len(exports), "functions")
