//! `lib/interval_tree.c` + `include/linux/interval_tree_generic.h` —
//! the `INTERVAL_TREE_DEFINE(struct interval_tree_node, rb, unsigned
//! long, __subtree_last, START, LAST,, interval_tree)` instantiation.
//!
//! In C the template is generic over the node struct, the rb field, the
//! endpoint type and the augmented field; here it is generic over the
//! index model: nodes are `&mut [RbNode]` pool entries and the
//! `start`/`last`/`__subtree_last` fields are parallel `Vec<u64>`
//! arrays in `ItData` — the analogue of ITSTART/ITLAST/ITSUBTREE
//! selection. A different instantiation supplies different arrays.

use klib::rbtree::*;

/// Dereference a `struct rb_node **` slot (klib's `link_get` is private;
/// `Link` is public and `rb_link_node` performs the store internally).
fn link_get(nodes: &[RbNode], root: &RbRoot, l: Link) -> usize {
    match l {
        Link::Root => root.rb_node,
        Link::Left(i) => nodes[i].left,
        Link::Right(i) => nodes[i].right,
    }
}

// ================= interval tree (lib/interval_tree.c) =================
//
// The INTERVAL_TREE_DEFINE(struct interval_tree_node, rb, unsigned long,
// __subtree_last, START, LAST,, interval_tree) instantiation. In the
// index model the "fields" of each node are parallel arrays in ItData —
// the generic-over-attribute part (ITSTART/ITLAST/ITSUBTREE) is the
// choice of which array each accessor reads.

pub struct ItData {
    pub start: Vec<u64>,
    pub last: Vec<u64>,
    /// `__subtree_last`: max `last` in the subtree, the augmented field.
    pub sub: Vec<u64>,
}

/// `RBNAME ## __compute` for a single max field (RB_DECLARE_CALLBACKS_MAX):
/// recompute node i's augmented field; returns true when unchanged and
/// `exit` is set (the propagate early-out).
pub fn it_compute(nodes: &[RbNode], ctx: &mut ItData, i: usize, exit: bool) -> bool {
    let old_aug = ctx.sub[i];
    let mut val = ctx.last[i]; /* ITLAST(node) */
    let r = nodes[i].right;
    if r != NIL && ctx.sub[r] > val {
        val = ctx.sub[r];
    }
    let l = nodes[i].left;
    if l != NIL && ctx.sub[l] > val {
        val = ctx.sub[l];
    }
    if exit && old_aug == val {
        return true;
    }
    ctx.sub[i] = val;
    false
}

pub fn it_propagate(nodes: &[RbNode], ctx: &mut ItData, mut rb: usize, stop: usize) {
    while rb != stop {
        if it_compute(nodes, ctx, rb, true) {
            break;
        }
        rb = rb_parent(nodes, rb);
    }
}

pub fn it_copy(_nodes: &[RbNode], ctx: &mut ItData, old: usize, new: usize) {
    ctx.sub[new] = ctx.sub[old];
}

pub fn it_rotate(nodes: &[RbNode], ctx: &mut ItData, old: usize, new: usize) {
    ctx.sub[new] = ctx.sub[old];
    it_compute(nodes, ctx, old, false);
}

pub fn it_merge(_nodes: &[RbNode], ctx: &mut ItData, node: usize, new: usize) {
    ctx.sub[node] = ctx.sub[node].max(ctx.sub[new]);
}

pub const IT_AUGMENT: Augment<ItData> = Augment {
    propagate: it_propagate,
    copy: it_copy,
    rotate: it_rotate,
    merge: it_merge,
};

/// `interval_tree_insert` — generated by INTERVAL_TREE_DEFINE.
pub fn interval_tree_insert(
    nodes: &mut [RbNode],
    ctx: &mut ItData,
    node: usize,
    root: &mut RbRootCached,
) {
    let mut link = Link::Root;
    let mut rb_parent_ = NIL;
    let start = ctx.start[node];
    let last = ctx.last[node];
    let mut leftmost = true;

    loop {
        let cur = link_get(nodes, &root.root, link);
        if cur == NIL {
            break;
        }
        rb_parent_ = cur;
        if ctx.sub[cur] < last {
            ctx.sub[cur] = last;
        }
        if start < ctx.start[cur] {
            link = Link::Left(cur);
        } else {
            link = Link::Right(cur);
            leftmost = false;
        }
    }

    ctx.sub[node] = last;
    rb_link_node(nodes, node, rb_parent_, link, &mut root.root);
    rb_insert_augmented_cached(nodes, node, root, leftmost, ctx, &IT_AUGMENT);
}

/// `interval_tree_remove`.
pub fn interval_tree_remove(
    nodes: &mut [RbNode],
    ctx: &mut ItData,
    node: usize,
    root: &mut RbRootCached,
) {
    rb_erase_augmented_cached(nodes, node, root, ctx, &IT_AUGMENT);
}

/// `interval_tree_subtree_search` — `node` must satisfy the loop
/// invariant start <= node->ITSUBTREE.
pub fn interval_tree_subtree_search(
    nodes: &[RbNode],
    ctx: &ItData,
    mut node: usize,
    start: u64,
    last: u64,
) -> usize {
    loop {
        let l = nodes[node].left;
        if l != NIL && start <= ctx.sub[l] {
            node = l;
            continue;
        }
        if ctx.start[node] <= last {
            /* Cond1 */
            if start <= ctx.last[node] {
                /* Cond2 */
                return node; /* node is leftmost match */
            }
            node = nodes[node].right;
            continue;
        }
        return NIL; /* No match */
    }
}

/// `interval_tree_iter_first`.
pub fn interval_tree_iter_first(
    nodes: &[RbNode],
    ctx: &ItData,
    root: &RbRootCached,
    start: u64,
    last: u64,
) -> usize {
    if root.root.rb_node == NIL {
        return NIL;
    }
    let node = root.root.rb_node;
    if ctx.sub[node] < start {
        return NIL;
    }
    let leftmost = root.rb_leftmost;
    if ctx.start[leftmost] > last {
        return NIL;
    }
    interval_tree_subtree_search(nodes, ctx, node, start, last)
}

/// `interval_tree_iter_next`.
pub fn interval_tree_iter_next(
    nodes: &[RbNode],
    ctx: &ItData,
    node0: usize,
    start: u64,
    last: u64,
) -> usize {
    let mut node = node0;
    let mut rb = nodes[node].right;

    loop {
        /* First, search right subtree if suitable */
        if rb != NIL && start <= ctx.sub[rb] {
            return interval_tree_subtree_search(nodes, ctx, rb, start, last);
        }

        /* Move up the tree until we come from a node's left child */
        loop {
            rb = rb_parent(nodes, node);
            if rb == NIL {
                return NIL;
            }
            let prev = node;
            node = rb;
            rb = nodes[node].right;
            if prev != rb {
                break;
            }
        }

        /* Check if the node intersects [start;last] */
        if last < ctx.start[node] {
            /* !Cond1 */
            return NIL;
        } else if start <= ctx.last[node] {
            /* Cond2 */
            return node;
        }
    }
}

// ---- span iterator (CONFIG_INTERVAL_TREE_SPAN_ITER) ----

/// `struct interval_tree_span_iter`. The start_hole/start_used and
/// last_hole/last_used unions alias one storage each, so a single
/// `span_start`/`span_last` pair models both.
pub struct SpanIter {
    pub nodes: [usize; 2],
    pub first_index: u64,
    pub last_index: u64,
    pub span_start: u64,
    pub span_last: u64,
    pub is_hole: i64,
}

/// `interval_tree_span_iter_next_gap`.
pub fn span_iter_next_gap(nodes: &[RbNode], ctx: &ItData, st: &mut SpanIter) {
    let mut cur = st.nodes[1];

    st.nodes[0] = cur;
    loop {
        if ctx.last[cur] > ctx.last[st.nodes[0]] {
            st.nodes[0] = cur;
        }
        cur = interval_tree_iter_next(nodes, ctx, cur, st.first_index, st.last_index);
        if !(cur != NIL
            && (ctx.last[st.nodes[0]] >= ctx.start[cur]
                || ctx.last[st.nodes[0]].wrapping_add(1) == ctx.start[cur]))
        {
            break;
        }
    }
    st.nodes[1] = cur;
}

/// `interval_tree_span_iter_first`.
pub fn span_iter_first(
    nodes: &[RbNode],
    ctx: &ItData,
    root: &RbRootCached,
    st: &mut SpanIter,
    first_index: u64,
    last_index: u64,
) {
    st.first_index = first_index;
    st.last_index = last_index;
    st.nodes[0] = NIL;
    st.nodes[1] = interval_tree_iter_first(nodes, ctx, root, first_index, last_index);
    if st.nodes[1] == NIL {
        /* No nodes intersect the span, whole span is hole */
        st.span_start = first_index;
        st.span_last = last_index;
        st.is_hole = 1;
        return;
    }
    if ctx.start[st.nodes[1]] > first_index {
        /* Leading hole on first iteration */
        st.span_start = first_index;
        st.span_last = ctx.start[st.nodes[1]] - 1;
        st.is_hole = 1;
        span_iter_next_gap(nodes, ctx, st);
        return;
    }

    /* Starting inside a used */
    st.span_start = first_index;
    st.is_hole = 0;
    span_iter_next_gap(nodes, ctx, st);
    st.span_last = ctx.last[st.nodes[0]];
    if st.span_last >= last_index {
        st.span_last = last_index;
        st.nodes[0] = NIL;
        st.nodes[1] = NIL;
    }
}

/// `interval_tree_span_iter_next`.
pub fn span_iter_next(nodes: &[RbNode], ctx: &ItData, st: &mut SpanIter) {
    if st.nodes[0] == NIL && st.nodes[1] == NIL {
        st.is_hole = -1;
        return;
    }

    if st.is_hole != 0 {
        st.span_start = st.span_last + 1;
        st.span_last = ctx.last[st.nodes[0]];
        if st.span_last >= st.last_index {
            st.span_last = st.last_index;
            st.nodes[0] = NIL;
            st.nodes[1] = NIL;
        }
        st.is_hole = 0;
        return;
    }

    if st.nodes[1] == NIL {
        /* Trailing hole */
        st.span_start = ctx.last[st.nodes[0]] + 1;
        st.span_last = st.last_index;
        st.nodes[0] = NIL;
        st.is_hole = 1;
        return;
    }

    /* must have both nodes[0] and [1], interior hole */
    st.span_start = ctx.last[st.nodes[0]] + 1;
    st.span_last = ctx.start[st.nodes[1]] - 1;
    st.is_hole = 1;
    span_iter_next_gap(nodes, ctx, st);
}

/// `interval_tree_span_iter_advance`.
pub fn span_iter_advance(
    nodes: &[RbNode],
    ctx: &ItData,
    root: &RbRootCached,
    st: &mut SpanIter,
    new_index: u64,
) {
    if st.is_hole == -1 {
        return;
    }
    st.first_index = new_index;
    if new_index > st.last_index {
        st.is_hole = -1;
        return;
    }

    /* Rely on the union aliasing hole/used */
    if st.span_start <= new_index && new_index <= st.span_last {
        st.span_start = new_index;
        return;
    }
    if new_index == st.span_last + 1 {
        span_iter_next(nodes, ctx, st);
    } else {
        span_iter_first(nodes, ctx, root, st, new_index, st.last_index);
    }
}
