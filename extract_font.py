#!/usr/bin/env python3
"""extract_font.py — extract lib/fonts/font_8x16.c fontdata into klib::font.

Reads the byte-identical upstream copy in ports/lib-font/ and emits
klib/src/font.rs. Pure-data extraction: the C file is an array literal;
we verify the extracted byte count against FONTDATAMAX (4096).
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).parent
SRC = ROOT / "ports" / "lib-font" / "font_8x16.c"
OUT = ROOT / "klib" / "src" / "font.rs"

src = SRC.read_text()
m = re.search(r"fontdata_8x16\s*=\s*\{\s*\{[^}]*\}\s*,\s*\{(.*?)\}\s*,?\s*\};", src, re.S)
assert m, "fontdata_8x16 array not found"
body = m.group(1)
# strip comments then collect hex bytes
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
data = [int(t, 16) for t in re.findall(r"0x([0-9a-fA-F]{2})", body)]
assert len(data) == 4096, f"expected FONTDATAMAX=4096 bytes, got {len(data)}"

lines = [
    "//! lib/fonts/font_8x16.c — VGA 8x16 font bitmap (generated by extract_font.py).",
    "//! 256 glyphs x 16 scanlines, MSB-left bit order, same layout as the C",
    "//! `fontdata_8x16` array. Do not edit by hand.",
    "",
    "/// Glyph width in pixels.",
    "pub const FONT_8X16_W: usize = 8;",
    "/// Glyph height in pixels.",
    "pub const FONT_8X16_H: usize = 16;",
    "/// Raw glyph data: `FONT_8X16[glyph * 16 + row]` is the row's 8-bit mask.",
    "pub const FONT_8X16: [u8; 4096] = [",
]
for i in range(0, 4096, 16):
    lines.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i+16]) + ",")
lines.append("];\n")
OUT.write_text("\n".join(lines))
print(f"wrote {OUT} ({len(data)} font bytes, {OUT.stat().st_size} file bytes)")
